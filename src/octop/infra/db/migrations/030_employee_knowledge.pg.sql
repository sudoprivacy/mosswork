-- Employee read grants for centrally managed knowledge bases.
CREATE TABLE IF NOT EXISTS employee_knowledge_bases (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kb_id TEXT NOT NULL REFERENCES knowledge_bases(knowledge_base_id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (user_id, kb_id)
);
CREATE INDEX IF NOT EXISTS idx_employee_knowledge_kb ON employee_knowledge_bases(kb_id);

-- Resource market schema: immutable imports and explicit administrator review.
CREATE TABLE IF NOT EXISTS market_resources (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    kind TEXT NOT NULL CHECK (kind IN ('skill', 'expert')),
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    owner_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    recommended_version_id TEXT,
    listed INTEGER NOT NULL DEFAULT 1 CHECK (listed IN (0, 1)),
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS market_drafts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id TEXT NOT NULL UNIQUE,
    resource_id TEXT NOT NULL REFERENCES market_resources(resource_id),
    version TEXT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('draft', 'submitted', 'rejected', 'published')),
    object_sha256 TEXT NOT NULL,
    manifest_json TEXT NOT NULL,
    inventory_json TEXT NOT NULL,
    file_count INTEGER NOT NULL,
    total_bytes BIGINT NOT NULL,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL,
    reviewed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    review_note TEXT NOT NULL DEFAULT '',
    reviewed_at BIGINT
);
CREATE INDEX IF NOT EXISTS idx_market_drafts_resource ON market_drafts(resource_id, created_at);
CREATE TABLE IF NOT EXISTS market_versions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id TEXT NOT NULL UNIQUE,
    resource_id TEXT NOT NULL REFERENCES market_resources(resource_id),
    version TEXT NOT NULL,
    draft_id TEXT NOT NULL UNIQUE REFERENCES market_drafts(draft_id),
    object_sha256 TEXT NOT NULL,
    manifest_json TEXT NOT NULL,
    published_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    published_at BIGINT NOT NULL,
    UNIQUE(resource_id, version)
);
CREATE INDEX IF NOT EXISTS idx_market_versions_resource ON market_versions(resource_id);
CREATE TABLE IF NOT EXISTS market_agent_installations (
    agent_id TEXT PRIMARY KEY REFERENCES agents(agent_id) ON DELETE CASCADE,
    version_id TEXT NOT NULL REFERENCES market_versions(version_id),
    lock_json TEXT NOT NULL,
    created_at BIGINT NOT NULL
);
